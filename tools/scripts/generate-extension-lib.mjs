#!/usr/bin/env node
/** Generate browser IIFE shims in apps/extension/lib/ from shared/ sources. */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import {
  FEEDBACK_MAX_LEN,
  FEEDBACK_PAGE_SIZE,
  MAX_EXCLUDED_KEYWORDS,
  MAX_KEYWORD_LENGTH,
} from "../../shared/site-config.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "../..");
const libDir = join(root, "apps/extension/lib");
const pureSourcePath = join(root, "shared/pure-logic.mjs");

const siteConfigJs = `/* Generated by tools/scripts/generate-extension-lib.mjs — do not edit. */
((root) => {
  root.AltteuriSiteConfig = Object.freeze({
    FEEDBACK_PAGE_SIZE: ${FEEDBACK_PAGE_SIZE},
    FEEDBACK_MAX_LEN: ${FEEDBACK_MAX_LEN},
    MAX_EXCLUDED_KEYWORDS: ${MAX_EXCLUDED_KEYWORDS},
    MAX_KEYWORD_LENGTH: ${MAX_KEYWORD_LENGTH},
  });
})(globalThis);
`;

function extractPureLogicBody(source) {
  return source
    .replace(/^import[^\n]+\n/gm, "")
    .replace(/^export \{[^\n]+\}\n/gm, "")
    .replace(/^export /gm, "");
}

const pureLogicJs = `/* Generated by tools/scripts/generate-extension-lib.mjs — do not edit. */
((root, factory) => {
  const api = Object.freeze(factory());
  root.Altteuri = root.Altteuri || {};
  root.Altteuri.pure = api;
  if (typeof module === "object" && module.exports) module.exports = api;
})(typeof globalThis === "object" ? globalThis : this, () => {
  const MAX_EXCLUDED_KEYWORDS = ${MAX_EXCLUDED_KEYWORDS};
  const MAX_KEYWORD_LENGTH = ${MAX_KEYWORD_LENGTH};

${extractPureLogicBody(readFileSync(pureSourcePath, "utf8"))}
  return {
    MAX_EXCLUDED_KEYWORDS,
    MAX_KEYWORD_LENGTH,
    compareNullableNumbers,
    compareDiscountRates,
    partitionAndSort,
    normalizedUnitPrice,
    normalizeExcludedKeyword,
    canAddExcludedKeyword,
    matchesExcludedKeyword,
    normalizeStoredSearchQuery
  };
});
`;

writeFileSync(join(libDir, "site-config.js"), siteConfigJs, "utf8");
writeFileSync(join(libDir, "pure-logic.js"), pureLogicJs, "utf8");
console.log("Generated apps/extension/lib/site-config.js and pure-logic.js");
