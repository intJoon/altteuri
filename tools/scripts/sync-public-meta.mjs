#!/usr/bin/env node
/** Sync manifest version into apps/web/public/version.json and related public assets. */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import {
  FEEDBACK_MAX_LEN,
  FEEDBACK_PAGE_SIZE,
} from "../../shared/site-config.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "../..");
const publicDir = join(root, "apps/web/public");
const manifest = JSON.parse(readFileSync(join(root, "apps/extension/manifest.json"), "utf8"));
const version = manifest.version || "0.0.0";

writeFileSync(
  join(publicDir, "version.json"),
  `${JSON.stringify({ version }, null, 2)}\n`,
  "utf8"
);

const siteConfigJs = `/* Generated by tools/scripts/sync-public-meta.mjs — do not edit. */
export const FEEDBACK_PAGE_SIZE = ${FEEDBACK_PAGE_SIZE};
export const FEEDBACK_MAX_LEN = ${FEEDBACK_MAX_LEN};
`;
writeFileSync(join(publicDir, "site-config.js"), siteConfigJs, "utf8");

function bumpStylesCache(html) {
  return html.replace(/styles\.css\?v=[^"']+/, `styles.css?v=${version}`);
}

for (const name of ["index.html", "404.html"]) {
  const htmlPath = join(publicDir, name);
  let html = readFileSync(htmlPath, "utf8");
  html = bumpStylesCache(html);
  writeFileSync(htmlPath, html, "utf8");
}

console.log(`Synced public meta for v${version}`);
